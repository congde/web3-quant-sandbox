export const ML_ALGORITHM_INDEX = Object.entries(KNOWLEDGE).map(([name, knowledge]) => ({ name, ...knowledge }));

export function getAlgorithmDetail(algorithm: MLAlgorithm, lesson: MLLesson): MLAlgorithmDetail {
  const knowledge = KNOWLEDGE[algorithm.name];
  if (!knowledge) {
    return {
      algorithm,
      lesson,
      era: "机器学习方法谱系",
      origin: `${algorithm.name} 属于 ${lesson.title} 的方法体系；本课程将其放回研究问题、数据契约与验证边界中理解。`,
      question: algorithm.purpose,
      intuition: `它的核心作用是：${algorithm.purpose}。`,
      equation: "目标 = 数据证据 + 模型假设 + 验证约束",
      variables: ["数据证据：冻结的历史样本", "模型假设：可检查的结构", "验证约束：时间样本外与成本"],
      useWhen: lesson.objective,
      value: lesson.caseStudy.decision,
      boundary: lesson.caseStudy.boundary,
      workflow: lesson.workflow,
      assumptions: lesson.checklist,
      failureModes: lesson.pitfalls,
    };
  }
  return {
    ...knowledge,
    algorithm,
    lesson,
    workflow: lesson.workflow,
    assumptions: lesson.checklist,
    failureModes: [knowledge.boundary, ...lesson.pitfalls],
  };
}
